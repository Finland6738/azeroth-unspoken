-- Authoring archive of Azeroth Unspoken (ADR 0027). Authoring store only: the game never reads it.
-- Lists (events, registers, depth, tags) and the conditions are JSON text in the intention row: that is the
-- authoritative value the exporter writes back. The tables intention_event / _register / _depth / _tag are search
-- indexes derived from it (rebuilt by `reindex`), never edited by hand. intention_motif does the same for the motifs.

CREATE TABLE meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- who writes and who reviews: the owner curates, AI sessions draft (decision D6 in #130)
CREATE TABLE author (
    id   TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('legacy', 'owner', 'ai', 'human')),
    note TEXT NOT NULL DEFAULT ''
);

-- a pack: one rules file and its texts in each language; `region` is the continent token of a regional pack
CREATE TABLE pack (
    id         TEXT PRIMARY KEY,
    name       TEXT NOT NULL DEFAULT '',
    region     TEXT,
    languages  TEXT NOT NULL DEFAULT '[]',
    rules_path TEXT NOT NULL
);

-- the folders as they are read: a file is prelude + chunks + epilogue (see packfiles.py). Generated by the importer,
-- never committed: it is what lets the exporter write unchanged entries back byte for byte.
CREATE TABLE source_file (
    path     TEXT NOT NULL,
    part     INTEGER NOT NULL DEFAULT 0,             -- a file can hold several tables (a language file of arcs)
    role     TEXT NOT NULL CHECK (role IN ('rules', 'texts', 'arcs', 'scripts', 'arc_texts')),
    pack_id  TEXT NOT NULL,
    region   TEXT,
    lang     TEXT,
    prelude  TEXT NOT NULL,
    epilogue TEXT NOT NULL,
    PRIMARY KEY (path, part)
);
CREATE TABLE source_chunk (
    path TEXT NOT NULL,
    part INTEGER NOT NULL DEFAULT 0,
    seq  INTEGER NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('gap', 'entry')),
    ref  TEXT,
    sig  TEXT,
    text TEXT NOT NULL,
    PRIMARY KEY (path, part, seq),
    FOREIGN KEY (path, part) REFERENCES source_file(path, part) ON DELETE CASCADE
);

-- an intention: one idea with all its variants and translations (decision D2 in #130: the unit that is counted)
CREATE TABLE intention (
    id            TEXT PRIMARY KEY,
    pack_id       TEXT NOT NULL REFERENCES pack(id),
    state         TEXT NOT NULL DEFAULT 'approved' CHECK (state IN ('draft', 'review', 'approved', 'retired')),
    author_id     TEXT NOT NULL REFERENCES author(id),
    events        TEXT NOT NULL,                 -- JSON list of events
    category      TEXT,
    speaker       TEXT,                          -- the voice: narrator | inner | character | npc
    form          TEXT,
    styles        TEXT,                          -- JSON list: the registers
    depth         TEXT,                          -- JSON list
    tags          TEXT,                          -- JSON list (trait tags, `stoicism>=60` thresholds and `emo:` tags, R4)
    theme         TEXT,                          -- one theme of the closed vocabulary (#90, Data/Themes.lua)
    motifs        TEXT,                          -- JSON list: zero to three motifs (#90)
    tier          TEXT,                          -- JSON: an explicit specificity tier (#89), a number or a name
    kind          TEXT,                          -- 'monologue' (#99): no texts, it chains the phrases in `parts`
    parts         TEXT,                          -- JSON list: the ids of the two or three parts of a monologue (#99)
    part_order    TEXT,                          -- the rule field `order` of a monologue: 'fixed' or 'free' (#99)
    chainable     TEXT,                          -- JSON: true or "only", the phrase may be a part of a monologue (#99)
    weight        NUMERIC,
    cooldown      NUMERIC,
    conditions    TEXT,                          -- JSON (a Lua condition table; R4 adds emotion, emotionMin/Max, traitMin/Max;
                                                 -- #100 adds `situation`, a composite situation of Data/Themes.lua)
    extra         TEXT,                          -- JSON: rule fields the archive does not model
    ctx           TEXT NOT NULL DEFAULT '*',     -- selection-index keys (ADR 0024), '*' = generic; comma separated
    region        TEXT,                          -- the region of its pack (NULL = every place)
    attribution   TEXT NOT NULL DEFAULT '',      -- who says an invented legend (decision D7 in #130)
    invented_lore INTEGER NOT NULL DEFAULT 0 CHECK (invented_lore IN (0, 1)),
    origin        TEXT NOT NULL DEFAULT 'folders' CHECK (origin IN ('folders', 'overlay'))
);
CREATE INDEX intention_state ON intention(state);
CREATE INDEX intention_pack ON intention(pack_id);

CREATE TABLE intention_event    (intention_id TEXT NOT NULL REFERENCES intention(id) ON DELETE CASCADE, ord INTEGER NOT NULL, value TEXT NOT NULL, PRIMARY KEY (intention_id, ord));
CREATE TABLE intention_register (intention_id TEXT NOT NULL REFERENCES intention(id) ON DELETE CASCADE, ord INTEGER NOT NULL, value TEXT NOT NULL, PRIMARY KEY (intention_id, ord));
CREATE TABLE intention_depth    (intention_id TEXT NOT NULL REFERENCES intention(id) ON DELETE CASCADE, ord INTEGER NOT NULL, value TEXT NOT NULL, PRIMARY KEY (intention_id, ord));
CREATE TABLE intention_tag      (intention_id TEXT NOT NULL REFERENCES intention(id) ON DELETE CASCADE, ord INTEGER NOT NULL, value TEXT NOT NULL, PRIMARY KEY (intention_id, ord));
CREATE TABLE intention_motif    (intention_id TEXT NOT NULL REFERENCES intention(id) ON DELETE CASCADE, ord INTEGER NOT NULL, value TEXT NOT NULL, PRIMARY KEY (intention_id, ord));
CREATE INDEX intention_event_value ON intention_event(value);
CREATE INDEX intention_motif_value ON intention_motif(value);
CREATE INDEX intention_theme ON intention(theme);
CREATE INDEX intention_tag_value ON intention_tag(value);

-- the texts: variants of an intention in a language (same meaning and register, different rhythm and words)
CREATE TABLE variant (
    intention_id TEXT NOT NULL REFERENCES intention(id) ON DELETE CASCADE,
    lang         TEXT NOT NULL,
    ord          INTEGER NOT NULL,
    text         TEXT NOT NULL,
    depth        TEXT,
    PRIMARY KEY (intention_id, lang, ord)
);

-- review states: draft -> review -> approved -> retired; ids are timestamps so that two branches rarely collide
CREATE TABLE review (
    id           TEXT PRIMARY KEY,
    intention_id TEXT NOT NULL,                  -- no foreign key: the history outlives an intention
    reviewer     TEXT NOT NULL REFERENCES author(id),
    verdict      TEXT NOT NULL CHECK (verdict IN ('approved', 'changes', 'retired', 'comment')),
    note         TEXT NOT NULL DEFAULT '',
    date         TEXT NOT NULL
);
CREATE TABLE changelog (
    id           TEXT PRIMARY KEY,
    date         TEXT NOT NULL,
    author       TEXT NOT NULL,
    action       TEXT NOT NULL,
    intention_id TEXT NOT NULL,
    from_state   TEXT,
    to_state     TEXT,
    note         TEXT NOT NULL DEFAULT ''
);

-- Story Arcs (ADR 0021) as data (#143): the definition is the table of `NS:RegisterArcs` kept as JSON (states, choices, steps with
-- their events, waits and conditions), the journal texts of a language are the table of `NS:AddArcTexts`. The lines an arc
-- speaks are ordinary intentions (events arc_open, arc_step, arc_resolve; condition `arc`).
CREATE TABLE arc (
    id         TEXT PRIMARY KEY,
    pack_id    TEXT NOT NULL REFERENCES pack(id),
    definition TEXT NOT NULL                     -- JSON
);
CREATE TABLE arc_text (
    arc_id TEXT NOT NULL REFERENCES arc(id) ON DELETE CASCADE,
    lang   TEXT NOT NULL,
    text   TEXT NOT NULL,                        -- JSON: title, summary, states, choices, stateNames
    PRIMARY KEY (arc_id, lang)
);
-- search index derived from the definition, rebuilt by `reindex`: one row per step
CREATE TABLE arc_step (
    arc_id     TEXT NOT NULL REFERENCES arc(id) ON DELETE CASCADE,
    ord        INTEGER NOT NULL,
    from_state TEXT,
    to_state   TEXT,
    triggers   TEXT,                             -- JSON list of the `on` events
    wait       NUMERIC,
    choose     TEXT,
    PRIMARY KEY (arc_id, ord)
);

-- NPC Alive dialogue scripts (ADR 0020) as data (#143): `key` is the archetype ("innkeeper") or "npc:<npcID>".
CREATE TABLE script (
    key        TEXT PRIMARY KEY,
    pack_id    TEXT NOT NULL REFERENCES pack(id),
    definition TEXT NOT NULL                     -- JSON: role, npcID, extends, start, nodes, choices
);
-- search indexes derived from the definition, rebuilt by `reindex`: the nodes (what the NPC says: an event) and the replies
CREATE TABLE script_node (
    script_key TEXT NOT NULL REFERENCES script(key) ON DELETE CASCADE,
    node       TEXT NOT NULL,
    event      TEXT,
    replies    TEXT,                             -- JSON list of reply ids
    PRIMARY KEY (script_key, node)
);
CREATE TABLE script_reply (
    script_key TEXT NOT NULL REFERENCES script(key) ON DELETE CASCADE,
    reply      TEXT NOT NULL,
    go         TEXT,                             -- the node it leads to (NULL closes the dialogue)
    flag       TEXT,
    relation   TEXT,
    labels     TEXT,                             -- JSON: { "it": ..., "en": ... }
    PRIMARY KEY (script_key, reply)
);
CREATE INDEX script_node_event ON script_node(event);
