-- Active romance (ADR 0061, step R3): the lines of a romance with an NPC, tiers 1 (Courteous) and 2 (Intimate). Only the
-- rules; the texts are in AzerothUnspoken_enUS/Romance.lua and AzerothUnspoken_itIT/Romance.lua, the flirt answers in
-- Data/RomanceFlirts.lua. Systems/Romance.lua picks every one of these lines itself: the NPC's reply to a flirt
-- (npcd_romance_<outcome>) and the jealous opening of the beloved's dialogue, inside the dialogue window; the scenes of
-- the romance popup (romance_scene, the narrator's prose); a private thought after a flirt (romance_inner, through the
-- Director). None of them comes from /au event or the Director by itself (event guards), and none goes to chat.
--
-- How to read the ids (`rom.<what>.<tier or phase>.<who>`):
--   welcome, cold, refuse   the NPC's reply to a flirt;  jealous   the jealous opening;  scene   the popup;  inner   a thought
--   t1, t2                  the tone tier (romanceTier, spec point 9): every rule carries one (validator `romanceTier`)
--   n1, n2...               any NPC;  cheerful, gruff...   the NPC's temperament;  innkeeper, guard...   the NPC's role
--   glance, gift...         the kind of flirt (romanceKind);  beloved   the NPC is the beloved;  other   the character
--                           has a beloved who is someone else
-- Editorial rules (spec point 15): every text is courteous or modest; tier 2 never describes more than an embrace and
-- ends on a closing line (the popup fades to black); nothing about a minor; no promise the game does not keep; the NPC
-- never attributes a past or a decision to the character. Italian agrees with {g:} (the character) and {og:} (the NPC).
